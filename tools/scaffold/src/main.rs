//! `emulator-scaffold`: turns a resource provider's OpenAPI documents (as published
//! in Azure/azure-rest-api-specs) into the table the emulator mounts.
//!
//! For a provider it writes, under `services/<service>/`:
//!
//! * `src/scaffold.rs` — every resource type, the `api-version`s it is defined in,
//!   and every operation, as a `ScaffoldedProvider`. Regenerated on every run.
//! * `CONTRACT.md` — what the specification says about each type: operations, name
//!   constraints and properties. Regenerated on every run.
//!
//! and, the first time only, the crate itself plus its workspace and router wiring.
//! It also records where the specification came from (repository, path and
//! commit) in `.emulator/scaffolded-specs.json`, so a scaffold can be regenerated
//! from the same input.
//! Hand-written handlers are never touched: a type is implemented by registering a
//! `ResourceTypeHandler` for it before the scaffold in the crate's `register`.

mod model;
mod render;
mod spec;

use std::path::{Path, PathBuf};

const USAGE: &str = "\
emulator-scaffold — generate a service's scaffold from its OpenAPI specification

USAGE:
    emulator-scaffold --namespace <Microsoft.X> --service <name> --spec <dir> [--repo <dir>]
    emulator-scaffold data-plane --service <name> --name <NAME> --spec <dir>... [--repo <dir>]

With `data-plane`, writes services/<name>/src/data_scaffold.rs: the operations
of a data plane, for `azure-emulator coverage` to report on. --name is what the
data plane is called (\"Key Vault\"); each --spec is one version directory
holding its OpenAPI documents (.../data-plane/Secrets/stable/7.6).

OPTIONS:
    --namespace <NS>   Resource provider namespace, e.g. Microsoft.Storage
    --service <NAME>   Crate directory under services/, e.g. storage
    --spec <DIR>       Directory holding the provider's stable/ and preview/ version
                       directories (searched recursively)
    --repo <DIR>       Emulator repository root [default: .]
";

fn fail(message: impl std::fmt::Display) -> ! {
    eprintln!("error: {message}\n\n{USAGE}");
    std::process::exit(2);
}

/// `emulator-scaffold data-plane`: lists a data plane's operations.
fn data_plane(mut args: impl Iterator<Item = String>) {
    let (mut service, mut name, mut spec_dirs) = (None, None, Vec::new());
    let mut repo = PathBuf::from(".");
    while let Some(arg) = args.next() {
        let mut value = || args.next().unwrap_or_else(|| fail(format!("{arg} needs a value")));
        match arg.as_str() {
            "--service" => service = Some(value()),
            "--name" => name = Some(value()),
            "--spec" => spec_dirs.push(PathBuf::from(value())),
            "--repo" => repo = PathBuf::from(value()),
            other => fail(format!("unknown option '{other}'")),
        }
    }
    let service = service.unwrap_or_else(|| fail("--service is required"));
    let name = name.unwrap_or_else(|| fail("--name is required"));
    if spec_dirs.is_empty() {
        fail("--spec is required");
    }
    // (path, method) -> operationId, so the listing is sorted and has no repeats.
    let mut operations = std::collections::BTreeMap::new();
    let mut api_version = String::new();
    for dir in &spec_dirs {
        let mut files: Vec<PathBuf> = std::fs::read_dir(dir)
            .unwrap_or_else(|e| fail(format!("reading {}: {e}", dir.display())))
            .filter_map(|entry| entry.ok().map(|e| e.path()))
            .filter(|path| path.extension().is_some_and(|e| e == "json"))
            .collect();
        files.sort();
        for file in files {
            let text = std::fs::read_to_string(&file).unwrap_or_else(|e| fail(format!("reading {}: {e}", file.display())));
            let document: serde_json::Value =
                serde_json::from_str(&text).unwrap_or_else(|e| fail(format!("{} is not JSON: {e}", file.display())));
            let Some(paths) = document.get("paths").and_then(|p| p.as_object()).filter(|p| !p.is_empty()) else {
                continue;
            };
            if let Some(version) = document.pointer("/info/version").and_then(|v| v.as_str()) {
                if api_version.as_str() < version {
                    api_version = version.to_string();
                }
            }
            for (path, methods) in paths {
                for (method, operation) in methods.as_object().into_iter().flatten() {
                    if !["get", "put", "post", "patch", "delete", "head"].contains(&method.as_str()) {
                        continue;
                    }
                    let id = operation.get("operationId").and_then(|v| v.as_str()).unwrap_or_default();
                    operations.insert((path.clone(), method.to_ascii_uppercase()), id.to_string());
                }
            }
        }
    }
    if operations.is_empty() {
        fail("no operations found in the --spec directories");
    }
    let mut source = String::from(
        "// @generated by emulator-scaffold from the data plane's OpenAPI specification.\n// Do not edit: rerun the generator instead. See tools/scaffold.\n\nuse emulator_core::dataplane::{DataOperation as Op, DataPlane};\n\n#[rustfmt::skip]\npub static DATA_PLANE: DataPlane = DataPlane {\n",
    );
    source.push_str(&format!("    name: {name:?},\n    api_version: {api_version:?},\n    operations: &[\n"));
    for ((path, method), id) in &operations {
        source.push_str(&format!("        Op {{ id: {id:?}, method: {method:?}, path: {path:?} }},\n"));
    }
    source.push_str("    ],\n};\n");
    let file = repo.join("services").join(&service).join("src/data_scaffold.rs");
    std::fs::write(&file, source).unwrap_or_else(|e| fail(format!("writing {}: {e}", file.display())));
    println!("{name}: {} operations, api-version {api_version}", operations.len());
    println!("  wrote {}", file.display());
    let entry = serde_json::json!({"dataPlane": name});
    match record_source(&repo, &format!("{service}-data-plane"), entry, &spec_dirs) {
        Ok(commit) => println!("  recorded specification commit {commit} in {SOURCES}"),
        Err(e) => eprintln!("warning: {SOURCES} not updated: {e}"),
    }
}

fn main() {
    if std::env::args().nth(1).is_some_and(|a| a == "data-plane") {
        return data_plane(std::env::args().skip(2));
    }
    let (mut namespace, mut service, mut spec_dir) = (None, None, None);
    let mut repo = PathBuf::from(".");
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        let mut value = || args.next().unwrap_or_else(|| fail(format!("{arg} needs a value")));
        match arg.as_str() {
            "--namespace" => namespace = Some(value()),
            "--service" => service = Some(value()),
            "--spec" => spec_dir = Some(PathBuf::from(value())),
            "--repo" => repo = PathBuf::from(value()),
            "-h" | "--help" => {
                print!("{USAGE}");
                return;
            }
            other => fail(format!("unknown option '{other}'")),
        }
    }
    let namespace = namespace.unwrap_or_else(|| fail("--namespace is required"));
    let service = service.unwrap_or_else(|| fail("--service is required"));
    let spec_dir = spec_dir.unwrap_or_else(|| fail("--spec is required"));
    if !service.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit()) || service.is_empty() {
        fail("--service must be lowercase letters and digits");
    }

    let versions = spec::discover_versions(&spec_dir);
    if versions.is_empty() {
        fail(format!("no stable/ or preview/ version directories under {}", spec_dir.display()));
    }
    let mut resolver = spec::Resolver::default();
    let provider = model::build(&namespace, &versions, &mut resolver);
    if provider.types.is_empty() && provider.operations.is_empty() {
        fail(format!("no operations for {namespace} found under {}", spec_dir.display()));
    }

    let crate_dir = repo.join("services").join(&service);
    let created = render::write_crate(&repo, &crate_dir, &service, &provider)
        .unwrap_or_else(|e| fail(format!("writing {}: {e}", crate_dir.display())));

    let operations: usize =
        provider.types.values().map(|t| t.operations.len()).sum::<usize>() + provider.operations.len();
    println!(
        "{namespace}: {} resource types, {operations} operations, {} api-versions",
        provider.types.len(),
        versions.len()
    );
    println!("  wrote {}", crate_dir.join("src/scaffold.rs").display());
    println!("  wrote {}", crate_dir.join("CONTRACT.md").display());
    if created {
        println!("  created crate service-{service} and wired it into the workspace and router");
    }
    match record_source(&repo, &service, serde_json::json!({"namespace": namespace}), std::slice::from_ref(&spec_dir)) {
        Ok(commit) => println!("  recorded specification commit {commit} in {SOURCES}"),
        Err(e) => eprintln!("warning: {SOURCES} not updated: {e}"),
    }
}

/// Where each provider's specification came from, relative to the repository root.
const SOURCES: &str = ".emulator/scaffolded-specs.json";

/// `git <args>` in `dir`, trimmed.
fn git(dir: &Path, args: &[&str]) -> Result<String, String> {
    let output = std::process::Command::new("git").arg("-C").arg(dir).args(args).output().map_err(|e| format!("running git: {e}"))?;
    if !output.status.success() {
        return Err(format!("{} is not in a git checkout", dir.display()));
    }
    Ok(String::from_utf8_lossy(&output.stdout).trim().to_string())
}

/// Records the specification checkout `spec_dirs` are in (its repository, the
/// paths inside it and the commit) as the source of what was generated for
/// `key`, together with the members of `entry`. Returns the commit.
fn record_source(repo: &Path, key: &str, mut entry: serde_json::Value, spec_dirs: &[PathBuf]) -> Result<String, String> {
    let first = spec_dirs.first().ok_or("no specification directory")?;
    let commit = git(first, &["rev-parse", "HEAD"])?;
    let mut paths = Vec::new();
    for dir in spec_dirs {
        if !git(dir, &["status", "--porcelain", "--", "."])?.is_empty() {
            return Err(format!("{} has uncommitted changes, so no commit describes it", dir.display()));
        }
        if git(dir, &["rev-parse", "HEAD"])? != commit {
            return Err("the --spec directories are at different commits".into());
        }
        paths.push(git(dir, &["rev-parse", "--show-prefix"])?.trim_end_matches('/').to_string());
    }
    let remote = git(first, &["remote", "get-url", "origin"]).unwrap_or_default();
    entry["repository"] = remote.strip_suffix(".git").unwrap_or(&remote).into();
    entry["commit"] = commit.clone().into();
    // One directory is a `path`; several are `paths`.
    match paths.as_slice() {
        [path] => entry["path"] = path.clone().into(),
        _ => entry["paths"] = paths.into(),
    }
    let file = repo.join(SOURCES);
    let mut sources: serde_json::Value = match std::fs::read_to_string(&file) {
        Ok(text) => serde_json::from_str(&text).map_err(|e| format!("{SOURCES} is not JSON: {e}"))?,
        Err(_) => serde_json::json!({}),
    };
    sources.as_object_mut().ok_or(format!("{SOURCES} is not an object"))?.insert(key.to_string(), entry);
    if let Some(parent) = file.parent() {
        std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    let text = serde_json::to_string_pretty(&sources).map_err(|e| e.to_string())?;
    std::fs::write(&file, text + "\n").map_err(|e| e.to_string())?;
    Ok(commit)
}
