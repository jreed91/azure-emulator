#!/usr/bin/env python3
"""Keeps the repository's GitHub issues in step with ``issues/``.

* A file in ``issues/things-that-do-not-work/`` without a GitHub issue gets one.
* A GitHub issue whose file has moved to ``issues/things-that-now-work/`` (or
  is gone) is closed as completed; one whose file is open again is reopened.

An issue belongs to a file through the marker ``<!-- issue-file: NAME -->`` in
its body, so issues opened by hand are never touched. The issue's title and
labels come from the file; its body is a short summary linking to the file,
which stays the source of truth.

    GITHUB_TOKEN=... GITHUB_REPOSITORY=owner/name python tools/issues/sync_github.py
    python tools/issues/sync_github.py --dry-run --issues listing.json   # no network

The workflow `.github/workflows/issues.yml` runs it on every push to main that
changes `issues/`.
"""

import argparse
import json
import os
import pathlib
import re
import sys
import time
import urllib.error
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[2]
OPEN = ROOT / "issues" / "things-that-do-not-work"
SERVICES = ROOT / "tests" / "fidelity" / "services.json"
MARKER = re.compile(r"<!-- issue-file: (\S+) -->")
KINDS = {
    "resource-type": "resource type",
    "provider-operation": "provider operation",
    "data-plane-operation": "data-plane operation",
    "known-gap": "known gap",
}
FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_"


def describe(path, repository):
    """The title, labels and body of the issue for one file."""
    text = path.read_text()
    lines = text.splitlines()
    header = dict(line.split(": ", 1) for line in lines[:3])
    title = next(line[2:] for line in lines if line.startswith("# "))
    paragraphs = text.split(f"# {title}", 1)[1].strip().split("\n\n")
    summary = paragraphs[0].strip()
    # A provider-level operation lists its paths in the paragraph after.
    if summary.startswith("This answers") and len(paragraphs) > 1:
        summary += "\n\n" + paragraphs[1].strip()
    kind, key = header["Issue-Kind"], header["Issue-Key"]
    if kind == "known-gap":
        area = json.loads(SERVICES.read_text()).get(key.split("::")[0]) or "the emulator"
    else:
        area = key.split("/")[0]
    link = f"https://github.com/{repository}/blob/main/issues/things-that-do-not-work/{path.name}"
    body = (
        f"{summary}\n\nDetails and what done means: [`issues/things-that-do-not-work/{path.name}`]({link}), "
        f"generated by `tools/issues/generate.py`.\n\n<!-- issue-file: {path.name} -->\n\n{FOOTER}"
    )
    return {"title": title, "labels": [KINDS[kind], area], "body": body}


def plan(files, issues):
    """What to do: [("create", name), ("close", number, name), ("reopen", number, name)].

    `files` is the set of open file names; `issues` is every issue as
    {"number", "state", "body"}. When two issues carry the same marker, the
    oldest is the one kept in step.
    """
    owned = {}
    for issue in sorted(issues, key=lambda i: i["number"]):
        found = MARKER.search(issue.get("body") or "")
        if found:
            owned.setdefault(found.group(1), issue)
    actions = [("create", name) for name in sorted(files) if name not in owned]
    for name, issue in sorted(owned.items()):
        if name in files and issue["state"] == "closed":
            actions.append(("reopen", issue["number"], name))
        elif name not in files and issue["state"] == "open":
            actions.append(("close", issue["number"], name))
    return actions


class GitHub:
    def __init__(self, repository, token):
        self.base = f"https://api.github.com/repos/{repository}"
        self.token = token

    def call(self, method, path, body=None):
        request = urllib.request.Request(
            self.base + path,
            method=method,
            data=None if body is None else json.dumps(body).encode(),
            headers={
                "Authorization": f"Bearer {self.token}",
                "Accept": "application/vnd.github+json",
                "X-GitHub-Api-Version": "2022-11-28",
                "User-Agent": "azure-emulator-issue-sync",
            },
        )
        for attempt in range(6):
            try:
                with urllib.request.urlopen(request) as response:
                    return json.loads(response.read() or b"null")
            except urllib.error.HTTPError as error:
                # Secondary rate limits answer 403 or 429; wait as told, or back off.
                if error.code in (403, 429) and attempt < 5:
                    wait = int(error.headers.get("Retry-After") or 60 * (attempt + 1))
                    print(f"rate limited; waiting {wait}s", flush=True)
                    time.sleep(wait)
                    continue
                raise SystemExit(f"{method} {path}: {error.code} {error.read().decode(errors='replace')}")

    def issues(self):
        found, page = [], 1
        while True:
            batch = self.call("GET", f"/issues?state=all&per_page=100&page={page}")
            if not batch:
                return found
            found += [i for i in batch if "pull_request" not in i]
            page += 1


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true", help="print what would change, change nothing")
    parser.add_argument("--issues", help="read the issues from this JSON file instead of GitHub (with --dry-run)")
    parser.add_argument("--pause", type=float, default=2.0, help="seconds between writes (GitHub limits how fast issues are made)")
    args = parser.parse_args()
    repository = os.environ.get("GITHUB_REPOSITORY", "jreed91/azure-emulator")
    files = {path.name for path in OPEN.glob("*.md")}

    if args.issues:
        issues = json.loads(pathlib.Path(args.issues).read_text())
        github = None
    else:
        token = os.environ.get("GITHUB_TOKEN")
        if not token:
            raise SystemExit("GITHUB_TOKEN is not set")
        github = GitHub(repository, token)
        issues = github.issues()

    actions = plan(files, issues)
    print(f"{len(files)} open file(s), {len(issues)} issue(s); {len(actions)} change(s)")
    for action in actions:
        name = action[-1]
        if args.dry_run or github is None:
            print("would", *action)
            continue
        if action[0] == "create":
            created = github.call("POST", "/issues", describe(OPEN / name, repository))
            print(f"opened #{created['number']} for {name}", flush=True)
        else:
            number = action[1]
            reopen = action[0] == "reopen"
            note = (
                f"`{name}` is back in `issues/things-that-do-not-work/`: this no longer works."
                if reopen
                else f"`{name}` has moved to `issues/things-that-now-work/`: the emulator now does this."
            )
            github.call("POST", f"/issues/{number}/comments", {"body": note})
            state = {"state": "open"} if reopen else {"state": "closed", "state_reason": "completed"}
            github.call("PATCH", f"/issues/{number}", state)
            print(f"{action[0]}d #{number} for {name}", flush=True)
        time.sleep(args.pause)
    return 0


if __name__ == "__main__":
    sys.exit(main())
